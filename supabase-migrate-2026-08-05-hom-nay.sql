-- -----------------------------------------------------------------------------
-- 0) Bảng cài đặt thời gian (bắt buộc cho /cai-dat)
-- -----------------------------------------------------------------------------
create table if not exists public.cai_dat_thoi_gian (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);

alter table public.cai_dat_thoi_gian
  add column if not exists hang_muc text,
  add column if not exists loai_cai_dat text,
  add column if not exists khung_gio text,
  add column if not exists ma_cai_dat text,
  add column if not exists ten_cai_dat text,
  add column if not exists gio_bat_dau time,
  add column if not exists gio_ket_thuc time,
  add column if not exists gia_tri text,
  add column if not exists nhom text default 'Chung',
  add column if not exists ghi_chu text;

alter table public.cai_dat_thoi_gian enable row level security;

drop policy if exists "cai_dat_thoi_gian_select_all" on public.cai_dat_thoi_gian;
create policy "cai_dat_thoi_gian_select_all"
  on public.cai_dat_thoi_gian for select
  using (true);

drop policy if exists "cai_dat_thoi_gian_insert_all" on public.cai_dat_thoi_gian;
create policy "cai_dat_thoi_gian_insert_all"
  on public.cai_dat_thoi_gian for insert
  with check (true);

drop policy if exists "cai_dat_thoi_gian_update_all" on public.cai_dat_thoi_gian;
create policy "cai_dat_thoi_gian_update_all"
  on public.cai_dat_thoi_gian for update
  using (true)
  with check (true);

drop policy if exists "cai_dat_thoi_gian_delete_all" on public.cai_dat_thoi_gian;
create policy "cai_dat_thoi_gian_delete_all"
  on public.cai_dat_thoi_gian for delete
  using (true);

comment on table public.cai_dat_thoi_gian is 'Cau hinh thoi gian he thong + key phan quyen (PERM_KEY_*).';


-- -----------------------------------------------------------------------------
-- 1) Bảng phiếu trộn vật tư định mức
-- -----------------------------------------------------------------------------
create table if not exists public.bang_tron_vat_tu_dinh_muc (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

alter table public.bang_tron_vat_tu_dinh_muc
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists ngay date,
  add column if not exists ma_lenh_sx text,
  add column if not exists tong_trong_luong numeric,
  add column if not exists ghi_chu text,
  add column if not exists chi_tiet jsonb not null default '[]'::jsonb,
  add column if not exists ma_sp text,
  add column if not exists ten_sp text,
  add column if not exists ma_nvl text,
  add column if not exists ten_nvl text,
  add column if not exists dinh_muc numeric,
  add column if not exists don_vi_dinh_muc text default '%';

create index if not exists bang_tron_vat_tu_dinh_muc_ngay_idx
  on public.bang_tron_vat_tu_dinh_muc (ngay desc);

create index if not exists bang_tron_vat_tu_dinh_muc_ma_lenh_sx_idx
  on public.bang_tron_vat_tu_dinh_muc (ma_lenh_sx);

alter table public.bang_tron_vat_tu_dinh_muc enable row level security;

drop policy if exists "bang_tron_vat_tu_dinh_muc_select_all" on public.bang_tron_vat_tu_dinh_muc;
create policy "bang_tron_vat_tu_dinh_muc_select_all"
  on public.bang_tron_vat_tu_dinh_muc for select using (true);

drop policy if exists "bang_tron_vat_tu_dinh_muc_insert_all" on public.bang_tron_vat_tu_dinh_muc;
create policy "bang_tron_vat_tu_dinh_muc_insert_all"
  on public.bang_tron_vat_tu_dinh_muc for insert with check (true);

drop policy if exists "bang_tron_vat_tu_dinh_muc_update_all" on public.bang_tron_vat_tu_dinh_muc;
create policy "bang_tron_vat_tu_dinh_muc_update_all"
  on public.bang_tron_vat_tu_dinh_muc for update using (true) with check (true);

drop policy if exists "bang_tron_vat_tu_dinh_muc_delete_all" on public.bang_tron_vat_tu_dinh_muc;
create policy "bang_tron_vat_tu_dinh_muc_delete_all"
  on public.bang_tron_vat_tu_dinh_muc for delete using (true);

comment on table public.bang_tron_vat_tu_dinh_muc is
  'Phieu tron dinh muc: lenh SX + san pham + dong NVL.';
comment on column public.bang_tron_vat_tu_dinh_muc.ma_lenh_sx is 'Ma lenh san xuat.';
comment on column public.bang_tron_vat_tu_dinh_muc.tong_trong_luong is
  'Tong trong luong (kg) denormalize tu SP dau (tuong thich cu).';
comment on column public.bang_tron_vat_tu_dinh_muc.chi_tiet is
  'Mang SP: [{ma_sp, ten_sp, tong_trong_luong, ghi_chu, nvl:[{ma_nvl, ten_nvl, gia_tri, don_vi, khoi_luong}]}]. 1 dong DB = 1 phieu.';


-- -----------------------------------------------------------------------------
-- 2) Bảng phiếu trộn thực tế (bổ sung ngày 2026-08-06)
-- -----------------------------------------------------------------------------
create table if not exists public.phieu_tron_thuc_te (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ngay date not null,
  ca text not null,
  dinh_muc_id uuid not null references public.bang_tron_vat_tu_dinh_muc(id) on delete cascade,
  ma_lenh_sx text,
  ghi_chu text,
  chi_tiet jsonb not null default '[]'::jsonb,
  constraint phieu_tron_thuc_te_dinh_muc_unique unique (dinh_muc_id)
);

create index if not exists phieu_tron_thuc_te_ngay_ca_idx
  on public.phieu_tron_thuc_te (ngay desc, ca);

alter table public.phieu_tron_thuc_te enable row level security;
drop policy if exists "phieu_tron_thuc_te_select_all" on public.phieu_tron_thuc_te;
create policy "phieu_tron_thuc_te_select_all" on public.phieu_tron_thuc_te for select using (true);
drop policy if exists "phieu_tron_thuc_te_insert_all" on public.phieu_tron_thuc_te;
create policy "phieu_tron_thuc_te_insert_all" on public.phieu_tron_thuc_te for insert with check (true);
drop policy if exists "phieu_tron_thuc_te_update_all" on public.phieu_tron_thuc_te;
create policy "phieu_tron_thuc_te_update_all" on public.phieu_tron_thuc_te for update using (true) with check (true);
drop policy if exists "phieu_tron_thuc_te_delete_all" on public.phieu_tron_thuc_te;
create policy "phieu_tron_thuc_te_delete_all" on public.phieu_tron_thuc_te for delete using (true);


